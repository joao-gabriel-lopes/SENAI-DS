CREATE DATABASE IF NOT EXISTS ESCOLA;

USE ESCOLA;

CREATE TABLE AVALIACAO(
    ID INT AUTO_INCREMENT PRIMARY KEY,
    ALUNO VARCHAR(50),
    MATERIA VARCHAR(50),
    NOTA INT
);

