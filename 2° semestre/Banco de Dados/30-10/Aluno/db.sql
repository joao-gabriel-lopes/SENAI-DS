#MÉDIA DA SALA
SELECT
    AVG(NOTA) AS MEDIA_SALA
FROM
    AVALIACAO;

#MÉDIA POR ALUNO
SELECT
    ALUNO,
    AVG(NOTA) AS MEDIA_ALUNO,
    SUM(NOTA) AS SOMA_NOTAS
FROM
    AVALIACAO
GROUP BY
    ALUNO;

#MÉDIA POR MATÉRIA
SELECT
    MATERIA,
    AVG(NOTA) AS MEDIA_MATERIA
FROM
    AVALIACAO
GROUP BY
    MATERIA;

#MÉDIA POR ALUNO E MATÉRIA
SELECT
    MATERIA,
    ALUNO,
    AVG(NOTA) AS MEDIA_ALUNO,
    SUM(NOTA) AS SOMA_NOTAS,
    CASE 
        WHEN AVG(NOTA) >= 7 THEN "APROVADO"
        ELSE "REPROVADO"
    END AS SITUACAO
FROM
    AVALIACAO
GROUP BY
    MATERIA,
    ALUNO;